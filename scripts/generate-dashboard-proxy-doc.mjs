import fs from 'node:fs';
import { loadTs } from '../tests/load-ts.mjs';

const { PROXY_RULES } = loadTs('dashboard/api/proxy-policy.ts');
const groups = new Map();
for (const rule of PROXY_RULES) {
  const [prefix, ...rest] = rule.path.split('/');
  const group = groups.get(prefix) ?? { methods: [], tags: new Set() };
  group.methods.push(`${rule.method} ${rest.join('/')}`);
  rule.tags.forEach(tag => group.tags.add(tag));
  groups.set(prefix, group);
}
const rows = [...groups].map(([prefix, group]) => `| ${prefix} | ${group.methods.map(method => '`' + method + '`').join('; ')} | ${[...group.tags].join(', ') || 'None'} |`);
fs.writeFileSync('docs/dashboard-proxy-allowlist.md', `# Dashboard proxy allowlist

Generated by \`npm run docs:dashboard-proxy\` from \`dashboard/api/proxy-policy.ts\`. The policy derives endpoint strings from the feature endpoint constants and is also consumed by the Route Handler. Extend that module when adding an endpoint, then regenerate this file.

Only these methods and paths may be forwarded beneath the configured backend's fixed \`/api/\` prefix. Numeric IDs and single safe slug segments are the only path substitutions. Methods and path casing are exact. Query strings do not grant additional paths or methods.

| Prefix | Allowed methods and suffixes | Tags expired after successful mutation |
| --- | --- | --- |
${rows.join('\n')}

Authentication endpoints are deliberately excluded from this relay: login, session inspection, and logout have dedicated handlers under \`/dashboard/api/session\`. Their responses never expose a token. Unsupported proxy paths or methods fail closed. Authentication, expiry, admin-role checks, CSRF checks, body limits, and header filtering apply independently of this table.
`);
